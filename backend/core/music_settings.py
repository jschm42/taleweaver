"""Server-wide music generation settings (``ServerSettings.music_settings``).

Music is generated by an admin-supplied ComfyUI workflow (experimental). The workflow is the
API-format JSON that ComfyUI exports with *Export (API)*; TaleWeaver fills placeholders in its
node inputs (see ``backend.engine.audio.music_workflow``) and never parses or alters anything else.
The concept for further providers (Google Lyria) is in ``docs/specs/music_generation.md``.
"""

from __future__ import annotations

import json
from typing import Any, Literal, Optional

from pydantic import BaseModel, Field, ValidationError, field_validator

MusicProvider = Literal["comfyui"]

MAX_WORKFLOW_BYTES = 512 * 1024
MAX_WORKFLOW_NODES = 500
PROMPT_PLACEHOLDER = "{{prompt}}"


class MusicSettings(BaseModel):
    """Admin settings for in-game music generation."""

    enabled: bool = False
    provider: MusicProvider = "comfyui"
    comfyui_url: str = "http://127.0.0.1:8188"
    comfyui_timeout: int = Field(default=900, ge=1, le=3600)
    # API-format ComfyUI graph: {node_id: {"class_type": ..., "inputs": {...}}}.
    comfyui_workflow: Optional[dict[str, Any]] = None
    comfyui_workflow_name: str = Field(default="", max_length=200)
    # Node whose "audio" output is downloaded; empty = the first node that reports audio.
    comfyui_output_node_id: str = Field(default="", max_length=64)
    default_duration: int = Field(default=30, ge=5, le=300)
    max_duration: int = Field(default=120, ge=5, le=600)
    # Generations a single play session may request (cost and GPU-time guard).
    max_generations_per_session: int = Field(default=20, ge=0, le=500)

    @field_validator("comfyui_workflow")
    @classmethod
    def _check_workflow(cls, value: Optional[dict[str, Any]]) -> Optional[dict[str, Any]]:
        if value is None:
            return None
        validate_music_workflow(value)
        return value


def _is_ui_format(workflow: dict[str, Any]) -> bool:
    return isinstance(workflow.get("nodes"), list) and "links" in workflow


def validate_music_workflow(workflow: Any) -> None:
    """Raise ``ValueError`` unless ``workflow`` is a usable API-format ComfyUI graph."""
    if not isinstance(workflow, dict) or not workflow:
        raise ValueError("The workflow must be a non-empty JSON object.")
    if _is_ui_format(workflow):
        raise ValueError(
            "This is a ComfyUI editor (UI) workflow. Export it with Workflow > Export (API)."
        )
    if len(workflow) > MAX_WORKFLOW_NODES:
        raise ValueError(f"The workflow has more than {MAX_WORKFLOW_NODES} nodes.")
    if len(json.dumps(workflow)) > MAX_WORKFLOW_BYTES:
        raise ValueError("The workflow is larger than 512 KiB.")
    for node_id, node in workflow.items():
        if not isinstance(node, dict) or not isinstance(node.get("class_type"), str):
            raise ValueError(f"Node '{node_id}' has no class_type; export the API format.")
        if not isinstance(node.get("inputs", {}), dict):
            raise ValueError(f"Node '{node_id}' has invalid inputs.")
    if PROMPT_PLACEHOLDER not in json.dumps(workflow):
        raise ValueError(
            "Put {{prompt}} into the text input of the workflow's prompt node "
            "(e.g. the tags field of the ACE-Step text encoder)."
        )


def normalize_music_settings(raw: Optional[dict[str, Any]]) -> dict[str, Any]:
    """Return stored settings with defaults; an invalid stored workflow is dropped."""
    data = dict(raw or {})
    try:
        return MusicSettings.model_validate(data).model_dump()
    except ValidationError:
        data.pop("comfyui_workflow", None)
        data["comfyui_workflow_name"] = ""
        return MusicSettings.model_validate(data).model_dump()


def public_music_settings(raw: Optional[dict[str, Any]]) -> dict[str, Any]:
    """Settings for the admin UI: the workflow itself is replaced by a short summary."""
    settings = normalize_music_settings(raw)
    workflow = settings.pop("comfyui_workflow")
    settings["has_workflow"] = workflow is not None
    settings["workflow_node_count"] = len(workflow or {})
    return settings


def is_music_available(raw: Optional[dict[str, Any]]) -> bool:
    """True when music generation is switched on and has everything it needs."""
    settings = normalize_music_settings(raw)
    return bool(settings["enabled"] and settings["comfyui_workflow"])
